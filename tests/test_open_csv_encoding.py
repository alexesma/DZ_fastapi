"""open_csv выбирает кодировку не по первой подошедшей, а по осмысленности текста.

Раньше первая кодировка, при которой файл резался на >1 колонку,
побеждала автоматически — а разделитель колонок это ASCII-символ, он
одинаково режет файл при любой однобайтной кодировке. Из-за этого
кириллический cp1251-файл мог быть прочитан как latin1 и превратиться
в "Äàò÷çàäíõîäà" вместо "Датчик заднего хода" (реальный случай,
всплывший в 598 карточках каталога).
"""

from dz_fastapi.services.process import open_csv


def test_cp1251_file_is_not_misread_as_latin1():
    text = "Бренд;Артикул;Наименование;Цена\nHONDA;12345;Датчик заднего хода;1000\n"
    df = open_csv(text.encode("cp1251"))

    assert df.iloc[1, 2] == "Датчик заднего хода"


def test_utf8_file_still_works():
    text = "Бренд;Артикул;Наименование;Цена\nHONDA;12345;Датчик заднего хода;1000\n"
    df = open_csv(text.encode("utf-8"))

    assert df.iloc[1, 2] == "Датчик заднего хода"
